const assert = require('node:assert/strict'), fs = require('node:fs'), path = require('node:path'), os = require('node:os');
const { summarize, validateSummary, describe } = require('../src/integration-summary');
const { ModuleCatalog } = require('../src/catalog');
const { buildModules } = require('../../scripts/build-modules');
const { fixture } = require('./test-browser-foundation');
const { moduleStates } = require('../src/module-state');

async function main() {
  const temporary = fs.mkdtempSync(path.join(os.tmpdir(), 'companion-integrations-')); let test;
  try {
    const full = buildModules(undefined, { output: path.join(temporary, 'all') });
    const validation = new ModuleCatalog({ directory: temporary, version: '1.3.3' }); validation.validate(full);
    assert.equal(full.modules.filter(m => m.integrations.phoneDeck).length, 27);
    assert.equal(full.modules.flatMap(m => m.integrations.phoneDeck?.controls || []).length, 91);
    assert.equal(JSON.stringify(full.modules.map(m => m.integrations)).includes('apiPrefix'), false);
    const manifests = full.modules.map(m => ({ manifest: JSON.parse(fs.readFileSync(path.join(__dirname, '../../modules', m.id, 'module.json'))) }));
    const phone = manifests.find(m => m.manifest.id === 'phone-deck').manifest;
    const context = { installed: [], catalog: full.modules, version: '1.3.3', capabilities: new Set(['windows', 'powershell', 'embedded-node']), states: new Map() };
    const absent = describe(phone, context);
    assert.equal(absent.required.length, 0, 'Phone Deck must remain OBS-only at its base');
    assert.equal(absent.optional.length, 26, 'Derive providers from contribution declarations, including uninstalled catalogue providers');
    assert.ok(absent.optional.every(m => m.installedVersion === null && m.compatible === null && m.catalogueOnly));
    assert.ok(absent.external.some(e => e.id === 'obs-websocket' && e.required));
    const legacy = structuredClone(full); for (const entry of legacy.modules) delete entry.integrations;
    validation.validate(legacy);
    const unknown = describe(legacy.modules.find(m => m.id === 'phone-deck'), { ...context, catalog: legacy.modules }, true);
    assert.equal(unknown.optional.length, 0); assert.equal(unknown.summaryKnown, false); assert.equal(unknown.unknownPhoneDeck, 30);
    const provider = manifests.find(m => m.manifest.id === 'local-ai');
    const installedContext = { ...context, installed: [provider], states: new Map([['local-ai', { state: 'ready' }]]) };
    const installedPhone = describe(phone, installedContext);
    assert.equal(installedPhone.optional.find(m => m.id === 'local-ai').catalogueOnly, false);
    assert.equal(installedPhone.optional.find(m => m.id === 'local-ai').hasService, true);
    provider.manifest.dependencies.companion = '>=99.0.0';
    assert.equal(describe(phone, installedContext).optional.find(m => m.id === 'local-ai').compatible, false);
    provider.manifest.dependencies.companion = '>=1.0.0';
    const walk = manifests.find(m => m.manifest.id === 'walk-ons').manifest;
    const walkDetails = describe(walk, context);
    assert.ok(walkDetails.optional.some(m => m.id === 'video'));
    assert.equal(walkDetails.required.some(m => m.id === 'video'), false);
    const spotify = describe(manifests.find(m => m.manifest.id === 'spotify').manifest, context);
    assert.ok(spotify.optional.some(m => m.id === 'countdown'));
    assert.ok(spotify.external.some(e => e.id === 'spotify-account'));
    assert.equal(spotify.optional.some(e => e.id === 'spotify-account'), false);
    const requirementsBefore = JSON.stringify(manifests.map(m => m.manifest.dependencies));
    const statesBefore = moduleStates(manifests, '1.3.3', context.capabilities, [], false);
    for (const item of manifests) describe(item.manifest, { ...context, installed: manifests, states: statesBefore.states });
    assert.equal(JSON.stringify(manifests.map(m => m.manifest.dependencies)), requirementsBefore);
    assert.deepEqual(moduleStates(manifests, '1.3.3', context.capabilities, [], false).states, statesBefore.states);
    assert.throws(() => validateSummary({ ...summarize(phone), phoneDeck: { transport: 'remote', controls: [] } }), /summary/);
    assert.throws(() => validateSummary({ ...summarize(phone), setup: [{ id: 'account', name: 'Account', required: 'true' }] }), /summary/);
    assert.throws(() => validateSummary({ ...summarize(phone), setup: [{ id: 123, name: 'Account', required: true }] }), /summary/);
    const damagedHints = { ...walk, ui: { ...walk.ui, optionalDependencies: 'unsupported-old-hint' } };
    const fallback = describe(damagedHints, context);
    assert.equal(fallback.summaryKnown, false); assert.ok(fallback.optional.some(m => m.id === 'video'));
    test = await fixture(path.join(temporary, 'host'));
    const before = JSON.stringify(test.host.services.config);
    const entry = test.host.catalog.catalog.modules.find(m => m.id === 'video');
    entry.integrations.phoneDeck.controls[0].name = 'Mismatched catalogue label';
    await assert.rejects(test.host.catalog.prepare('video'), /integration summary differs/);
    entry.integrations = summarize(JSON.parse(fs.readFileSync(path.join(__dirname, '../../modules/video/module.json'))));
    await test.host.installCatalogModule('video');
    const callsBefore = test.calls.length;
    const inventory = await test.host.listModules(), catalogue = await test.host.catalog.inventory();
    assert.ok(inventory.modules.every(m => m.integrationDetails));
    assert.ok(catalogue.modules.every(m => m.integrationDetails));
    assert.equal(test.calls.length, callsBefore); assert.equal(JSON.stringify(test.host.services.config), before);
    assert.equal(test.host.services.services.size, 0);
    console.log('Integrations passed: 29 deterministic summaries, 25 providers/78 visible controls, 24 optional Phone Deck integrations, old-catalogue unknown fallback, friendly setup separation, compatibility, unchanged dependency states, package-summary verification and effect-free inventory.');
  } finally { await test?.close(); assert.ok(path.resolve(temporary).startsWith(path.resolve(os.tmpdir()) + path.sep)); fs.rmSync(temporary, { recursive: true, force: true }); }
}
main().catch(error => { console.error(error); process.exitCode = 1; });
